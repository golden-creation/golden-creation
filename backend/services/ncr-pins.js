const DEFAULT_PIN_SET = new Set(DEFAULT_NCR_PINS.map((entry) => entry.pin));

export function defaultEligiblePinText() {
  return DEFAULT_NCR_PINS.map((entry) => entry.pin).join("\n");
}

export function normalizePin(value) {
  const digits = String(value ?? "").replace(/\D/g, "");
  return /^[1-9][0-9]{5}$/.test(digits) ? digits : "";
}

export function sanitizeEligiblePinText(value) {
  const tokens = String(value ?? "").split(/[\s,;]+/).map((token) => token.trim()).filter(Boolean);
  const invalid = tokens.filter((token) => !/^[1-9][0-9]{5}$/.test(token));
  if (invalid.length) {
    const error = new Error("Eligible PIN codes must be exact 6-digit India Post codes. City names and PIN prefixes are not accepted.");
    error.statusCode = 422;
    throw error;
  }
  return [...new Set(tokens)].join("\n");
}

export function eligiblePinSet(value) {
  if (value == null) return new Set(DEFAULT_PIN_SET);
  const pins = new Set();
  for (const token of String(value).split(/[^0-9]+/)) {
    if (/^[1-9][0-9]{5}$/.test(token)) pins.add(token);
  }
  return pins;
}

export function pinIsEligible(pin, allowlist = DEFAULT_PIN_SET) {
  const normalized = normalizePin(pin);
  return Boolean(normalized) && allowlist.has(normalized);
}
